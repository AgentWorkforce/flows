import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { root, source, declarations, declarationText, directExports, unionDeclarations, exportedNames, exportSources, literal, signatureText, starModule, ts, typeExports, typeReferences } from './authoring-source.mjs';

export const referencePaths = ['packages/surface/AUTHORING.md', 'docs/CLI.md'];
const regenerate = 'npm run gen:docs --prefix packages/surface';
// AUTHORING.md ships in the npm package, where repository-relative links
// resolve under node_modules; point at the published repository docs instead.
const repoDocs = 'https://github.com/AgentWorkforce/flows/blob/main/docs';
const fence = text => `\`\`\`ts\n${text}\n\`\`\`\n`;
const proseCell = value => cell(value).replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const cell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');

export function authoringReference() {
  const read = name => source(resolve(root, `packages/surface/src/${name}.ts`));
  const context = read('context');
  const flow = read('flow');
  const step = read('step');
  const completion = read('completion');
  const exports = exportedNames(read('index'));
  const dist = resolve(root, 'packages/surface/dist/index.d.ts');
  if (existsSync(dist) && JSON.stringify(exportedNames(source(dist))) !== JSON.stringify(exports)) {
    throw new Error('Surface dist exports differ from src; rebuild with bun run build in packages/surface');
  }
  const render = (file, name) => {
    if (!exports.includes(name)) throw new Error(`${name} is not exported by the surface`);
    return fence(declarationText(file, name));
  };
  let text = `# Authoring reference\n\nGenerated by \`scripts/generate-authoring-reference.mjs\` from the exported types in this checkout. Do not edit.\nRegenerate from the repository root with \`${regenerate}\`. Install tooling first with \`cd packages/surface && bun install --frozen-lockfile --ignore-scripts\`; no build is required.\n\nThis file describes signatures; [SURFACE.md](${repoDocs}/SURFACE.md) explains semantics and [CLI.md](${repoDocs}/CLI.md) lists commands. The shipped \`src/*.ts\` declarations are the canonical source for emitted \`dist/*.d.ts\`. These links follow \`main\`; for an installed release, read the same files at this repository's \`v<version>\` tag.\n\nSignatures cover this package. A type from a dependency, such as a helper client from \`@relayfile/relay-helpers\`, is named by its import line and not expanded; read its methods in that package's typings.\n\nCheck this reference with \`bun run check:docs\` in \`packages/surface\` after any surface, SDK, CLI or generator change. CI does not run that check yet.\n\n## Flow declarations\n\n`;
  text += render(flow, 'flow') + '\n' + render(flow, 'FlowHeader');
  text += '\nSupporting declaration types (not all are package-level exports):\n\n';
  for (const name of ['HelperTools', 'FlowBody', 'FlowHandle', 'TriggeredFlowHandle']) text += fence(declarationText(flow, name)) + '\n';
  text += '\n## Context\n\n' + render(context, 'Ctx');
  text += '\n## Options and results\n\n';
  for (const name of ['RunOptions', 'RunResult', 'AgentOptions', 'PermissionsSpec', 'AgentResult', 'LlmOptions', 'DispatchResult', 'DoneOptions']) {
    text += `### ${name}\n\n${render(context, name)}\n`;
  }
  text += '## Completion vocabularies\n\nAuthored `f.done` verdicts, kernel run outcomes and step outcomes are distinct closed vocabularies.\n\n| Vocabulary | Type | Used for | Values |\n| --- | --- | --- | --- |\n';
  for (const [name, type, use] of [['FLOW_COMPLETION_REASONS', 'FlowCompletionReason', 'f.done'], ['RUN_COMPLETION_REASONS', 'RunCompletionReason', 'Kernel run completion'], ['COMPLETION_REASONS', 'CompletionReason', 'Journal step completion']]) {
    if (!exports.includes(type)) throw new Error(`${type} is not exported by the surface`);
    text += `| \`${name}\` | \`${type}\` | ${use} | ${literal(completion, name).map(value => `\`${value}\``).join(', ')} |\n`;
  }
  text += '\n## Gates\n\n' + render(step, 'Step') + '\n';
  text += 'Named gate members are shown even when they are not individually exported from the package.\n\n';
  text += unionDeclarations(step, 'NamedGate').map(fence).join('\n');
  text += `\nThe kernel verification fields are \`exit_code\`, \`output_contains\` and \`json_schema\`. Named gates are data lowered by the SDK. Only a named gate is inspectable before execution; a predicate gate records its verdict at runtime. See [the gate contract](${repoDocs}/SURFACE.md#6-the-gate-contract-and-remaining-open-surface-questions).\n`;
  const helpers = declarations(read('helpers/index'), 'Helpers')[0].members;
  const providers = literal(read('helpers/providers'), 'helperProviders');
  text += `\n## Helper namespaces\n\n\`Ctx extends Helpers\` exposes ${helpers.length} namespaces. \`f.mcp\` is an additional context member. \`f.slack\` is included in Helpers; see [Slack semantics](${repoDocs}/SLACK-HELPER.md). Resource counts describe the pinned adapter catalog, not bespoke helper methods or an assurance of credentials.\n\n| Namespace | Type | Pinned adapter resources |\n| --- | --- | --- |\n`;
  for (const member of helpers) {
    const name = member.name.text;
    const provider = providers.find(item => item.namespace === name);
    if (!provider) throw new Error(`Missing helper provider metadata: ${name}`);
    text += `| \`f.${name}\` | \`${member.type.getText()}\` | ${provider.supported ? provider.resources.length : 'None in pinned catalog'} |\n`;
  }
  text += '\n## Triggers\n\nSources for `flow(name, { on }, body)` and `f.on(source, options)`.\n\n';
  const triggers = read('triggers');
  const schedules = read('schedule');
  text += fence(signatureText(triggers, 'webhook')) + '\n' + fence(signatureText(schedules, 'schedule'));
  text += providerTriggers();
  text += otherFunctions(text, exports);
  text += '\n## Referenced declarations\n\nEvery type named by a declaration above or by the helper namespace table, followed transitively through the file that names it. Dependency types are named by import; completion reasons and `Helpers` are the tables above.\n\n';
  // Helper namespace types appear only in the table above, and a type-only
  // export may be named by no signature at all; declare every public type.
  const helperTypes = helpers.map(member => ({ name: member.type.getText(), from: resolve(root, 'packages/surface/src/helpers/index.ts') }));
  text += referencedDeclarations(text, exports, [...helperTypes, ...typeExports(read('index'))]);
  return text.replace(/\n+$/, '\n');
}

/**
 * Generated provider trigger constructors, reached from the package root only
 * through `export *`. Each method returns `providerTrigger(provider, event, ...)`;
 * the table reads the provider and event literals from that call.
 */
function providerTriggers() {
  const index = source(resolve(root, 'packages/surface/src/index.ts'));
  const rows = [];
  const values = [];
  for (const star of index.statements.filter(ts.isExportDeclaration)) {
    const barrel = starModule(index, star);
    if (barrel === undefined) continue;
    const barrelFile = source(barrel);
    for (const name of directExports(barrelFile)) {
      const statement = barrelFile.statements.find(node => (ts.isVariableStatement(node) ? node.declarationList.declarations : [node]).some(item => item.name?.text === name));
      const doc = ts.getJSDocCommentsAndTags(ts.isVariableStatement(statement) ? statement.declarationList.declarations[0] : statement)
        .map(item => ts.getTextOfJSDocComment(item.comment)).filter(Boolean).join(' ');
      if (!doc) throw new Error(`${barrel}: exported ${name} has no JSDoc to document`);
      values.push(`- \`${name}\`: ${doc}`);
    }
    for (const entry of barrelFile.statements.filter(ts.isExportDeclaration)) {
      if (!entry.exportClause || !ts.isNamedExports(entry.exportClause)) throw new Error(`${barrel}: unsupported re-export`);
      const file = source(resolve(dirname(barrel), entry.moduleSpecifier.text.replace(/\.js$/, '.ts')));
      for (const item of entry.exportClause.elements) {
        const namespace = item.name.text;
        const declaration = file.statements.filter(ts.isVariableStatement)
          .flatMap(statement => statement.declarationList.declarations)
          .find(candidate => candidate.name.getText(file) === (item.propertyName?.text ?? namespace));
        const object = declaration?.initializer?.arguments?.[0];
        if (!object || !ts.isObjectLiteralExpression(object)) throw new Error(`${file.fileName}: ${namespace} is not a frozen trigger object`);
        for (const method of object.properties) {
          const call = ts.isMethodDeclaration(method) && method.body?.statements.length === 1
            && ts.isReturnStatement(method.body.statements[0]) ? method.body.statements[0].expression : undefined;
          if (!call || !ts.isCallExpression(call) || call.expression.getText(file) !== 'providerTrigger'
            || !ts.isStringLiteral(call.arguments[0]) || !ts.isStringLiteral(call.arguments[1])) {
            throw new Error(`${file.fileName}: ${namespace}.${method.name?.getText(file)} does not return providerTrigger(provider, event)`);
          }
          const params = method.parameters.map(parameter => parameter.getText(file)).join(', ');
          rows.push(`| \`${namespace}.${method.name.getText(file)}(${cell(params)})\` | \`${call.arguments[0].text}\` | \`${call.arguments[1].text}\` |`);
        }
      }
    }
  }
  if (rows.length === 0) return '';
  return '\n### Provider triggers\n\nExported from the package root (`import { github } from \'@relayflows/surface\'`). '
    + 'Each call returns `ProviderTriggerSource<Provider, Event>` for the listed provider and event; pass it to `flow(...).on(...)` or `f.on(...)`.\n\n'
    + '| Call | Provider | Event |\n| --- | --- | --- |\n' + rows.join('\n') + '\n'
    + (values.length ? `\nAlso exported alongside the constructors, keyed by the Provider column:\n\n${values.join('\n')}\n` : '');
}

/** Every other function exported from the package root, so the reference covers each callable. */
function otherFunctions(rendered, exports) {
  const modules = exportSources(source(resolve(root, 'packages/surface/src/index.ts')));
  const fences = [];
  for (const name of exports) {
    const module = modules.get(name);
    if (module === undefined || !module.startsWith('.')) continue;
    const located = functionModule(resolve(root, 'packages/surface/src', module.replace(/\.js$/, '.ts')), name);
    if (located === undefined || new RegExp(`export function ${name}[<(]`).test(rendered)) continue;
    fences.push(fence(signatureText(located.file, located.name)));
  }
  return fences.length === 0 ? '' : `\n## Other exported functions\n\nScheduling, cron and writeback utilities exported from the package root.\n\n${fences.join('\n')}`;
}

/** The file and local name of a function declaration, following in-package re-exports. */
function functionModule(path, name, seen = new Set()) {
  if (seen.has(path)) return undefined;
  seen.add(path);
  const file = source(path);
  if (file.statements.some(node => ts.isFunctionDeclaration(node) && node.name?.text === name)) return { file, name };
  const reexport = file.statements.find(node => ts.isExportDeclaration(node) && node.moduleSpecifier
    && node.exportClause && ts.isNamedExports(node.exportClause) && node.exportClause.elements.some(item => item.name.text === name));
  const item = reexport?.exportClause.elements.find(element => element.name.text === name);
  if (!item || !reexport.moduleSpecifier.text.startsWith('.')) return undefined;
  return functionModule(resolve(dirname(path), reexport.moduleSpecifier.text.replace(/\.js$/, '.ts')), item.propertyName?.text ?? name, seen);
}

/**
 * Declare every type the reference names, so no signature points into dist/.
 * A name is resolved where it is used: a package-root export through the
 * index, anything else through the referencing file's own declarations and
 * imports. A dependency's type is named by an import line, not copied, and
 * TypeScript globals and type parameters resolve to nothing and are skipped.
 */
function referencedDeclarations(rendered, exports, seeds = []) {
  const srcRoot = resolve(root, 'packages/surface/src');
  const index = resolve(srcRoot, 'index.ts');
  const modules = exportSources(source(index));
  const fenced = text => [...text.matchAll(/```ts\n([\s\S]*?)```/g)].map(match => match[1]).join('\n');
  const declared = (text, name) => new RegExp(`(?:(?:interface|type|function|const|class) ${name}\\b|(?:export|import)(?: type)? \\{ ${name} \\} from)`).test(text);
  const tabulated = new Set(['Helpers', 'FlowCompletionReason', 'RunCompletionReason', 'CompletionReason']);
  let body = fenced(rendered);
  let out = '';
  const done = new Set();
  const queue = [...typeReferences(body).map(name => ({ name, from: index })),
    ...seeds];
  while (queue.length) {
    const { name, from } = queue.shift();
    if (done.has(name) || tabulated.has(name) || declared(body, name)) continue;
    const module = exports.includes(name) ? modules.get(name) : undefined;
    const found = module !== undefined && module.startsWith('.')
      ? declarationOf(resolve(srcRoot, module.replace(/\.js$/, '.ts')), name)
      : resolveFrom(from, name);
    if (found === undefined) continue;
    done.add(name);
    const note = exports.includes(name) ? '' : ' (not exported from the package root)';
    out += `### ${name}${found.external ? '' : note}\n\n${fence(found.text)}\n`;
    body += `\n${found.text}`;
    if (found.path !== undefined) queue.push(...typeReferences(found.text).map(next => ({ name: next, from: found.path })));
  }
  return out;
}

/** `name` as the file at `path` sees it: its own declaration, or what it imports under that name. */
function resolveFrom(path, name) {
  const file = source(path);
  if (file.statements.some(node => node.name?.text === name && !ts.isImportDeclaration(node))) {
    return { text: declarationText(file, name), path };
  }
  for (const node of file.statements.filter(ts.isImportDeclaration)) {
    const bindings = node.importClause?.namedBindings;
    const item = bindings && ts.isNamedImports(bindings) && bindings.elements.find(element => element.name.text === name);
    if (!item) continue;
    const target = node.moduleSpecifier.text;
    if (target.startsWith('.')) return declarationOf(resolve(dirname(path), target.replace(/\.js$/, '.ts')), item.propertyName?.text ?? name);
    const typeOnly = node.importClause.isTypeOnly || item.isTypeOnly;
    return { text: `import${typeOnly ? ' type' : ''} { ${name} } from ${JSON.stringify(target)};`, external: true };
  }
  return undefined;
}

/**
 * The declaration of `name` in `path`, following in-package re-exports to the
 * declaring file. A dependency's type is named, not copied: its source is not
 * part of this package.
 */
function declarationOf(path, name, seen = new Set()) {
  if (seen.has(path)) throw new Error(`${path}: cyclic re-export of ${name}`);
  seen.add(path);
  const file = source(path);
  const implemented = file.statements.find(node => ts.isFunctionDeclaration(node) && node.body && node.name?.text === name);
  if (implemented !== undefined) {
    // A typed signature is the contract; an inferred return type is only stated by its implementation.
    return { path, text: implemented.type ? signatureText(file, name)
      : `// Return type inferred from this implementation.\n${usedImports(file, implemented)}${file.text.slice(implemented.getFullStart(), implemented.end).trim()}` };
  }
  if (file.statements.some(node => node.name?.text === name)) return { text: declarationText(file, name), path };
  const reexport = file.statements.find(node => ts.isExportDeclaration(node) && node.moduleSpecifier
    && node.exportClause && ts.isNamedExports(node.exportClause) && node.exportClause.elements.some(item => item.name.text === name));
  if (!reexport) throw new Error(`${path}: missing declaration ${name}`);
  const item = reexport.exportClause.elements.find(element => element.name.text === name);
  const original = item.propertyName?.text ?? name;
  const target = reexport.moduleSpecifier.text;
  if (target.startsWith('.')) return declarationOf(resolve(dirname(path), target.replace(/\.js$/, '.ts')), original, seen);
  return { text: `export type { ${name} } from ${JSON.stringify(target)};`, external: true };
}

/** The import lines binding identifiers `node` uses, narrowed to those names, so a copied body names its sources. */
function usedImports(file, node) {
  const used = new Set();
  (function visit(child) { if (ts.isIdentifier(child)) used.add(child.text); ts.forEachChild(child, visit); })(node);
  return file.statements.filter(ts.isImportDeclaration).flatMap(statement => {
    const bindings = statement.importClause?.namedBindings;
    const items = bindings && ts.isNamedImports(bindings) ? bindings.elements.filter(item => used.has(item.name.text)) : [];
    if (items.length === 0) return [];
    const typeOnly = statement.importClause.isTypeOnly ? ' type' : '';
    return [`import${typeOnly} { ${items.map(item => item.getText(file)).join(', ')} } from ${JSON.stringify(statement.moduleSpecifier.text)};\n`];
  }).join('');
}

export function cliReference() {
  const file = source(resolve(root, 'packages/sdk/src/cli-commands.ts'));
  let text = `# CLI reference\n\nGenerated from \`packages/sdk/src/cli-commands.ts\` by \`scripts/generate-authoring-reference.mjs\`. Do not edit. Regenerate with \`${regenerate}\`.\n\nSee [SURFACE.md](SURFACE.md#5-invocation-the-cli) for execution semantics and [CLOUD.md](CLOUD.md) for hosted operations.\n`;
  function render(command, parent = 'flows') {
    const invocation = `${parent} ${command.name}`;
    text += `\n## ${invocation}\n\n${command.description}\n`;
    if (command.aliases) text += `\nAliases: ${command.aliases.map(alias => `\`${alias}\``).join(', ')}.\n`;
    if (command.args?.length) {
      text += '\n| Argument | Required | Description |\n| --- | --- | --- |\n';
      for (const arg of command.args) text += `| \`${cell(arg.name)}${arg.variadic ? '...' : ''}\` | ${arg.required ? 'Yes' : 'No'} | ${proseCell(arg.description)} |\n`;
    }
    if (command.options?.length) {
      text += '\n| Option | Description | Default |\n| --- | --- | --- |\n';
      for (const option of command.options) text += `| \`${cell(option.flags)}\` | ${proseCell(option.description)} | ${option.defaultValue === undefined ? '—' : `\`${cell(option.defaultValue)}\``} |\n`;
    }
    for (const child of command.subcommands ?? []) render(child, invocation);
  }
  text += '\n## Global options\n\nAccepted only as the sole argument, before any verb.\n\n| Option | Description |\n| --- | --- |\n';
  for (const option of literal(file, 'CLI_GLOBAL_OPTIONS')) text += `| \`${cell(option.flags)}\` | ${proseCell(option.description)} |\n`;
  for (const command of literal(file, 'CLI_VERBS')) render(command);
  return text;
}
export function generate(outDir = root) {
  for (const [index, text] of [authoringReference(), cliReference()].entries()) {
    const file = resolve(outDir, referencePaths[index]);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.length && (args.length !== 2 || args[0] !== '--out-dir')) throw new Error('Usage: generate-authoring-reference.mjs [--out-dir <directory>]');
  generate(args[1]);
  console.log('AUTHORING_REFERENCE_GENERATED');
}

import assert from 'node:assert/strict';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { deflateRawSync, inflateRawSync } from 'node:zlib';

const { values } = parseArgs({ options: { check: { type: 'boolean' } } });
const sdk = fileURLToPath(new URL('../packages/sdk/', import.meta.url));
const require = createRequire(join(sdk, 'package.json'));
const engine = require.resolve('re2js'); // Select the require (CJS) export.
const raw = readFileSync(engine);
let directory = dirname(engine);
let version;
while (true) {
  const manifest = join(directory, 'package.json');
  if (existsSync(manifest)) {
    const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
    if (pkg.name === 're2js') { version = pkg.version; break; }
  }
  const parent = dirname(directory);
  assert.notEqual(parent, directory, 'Cannot find the resolved re2js package manifest');
  directory = parent;
}
assert.equal(typeof version, 'string');
const compressed = deflateRawSync(raw, { level: 9 });
const inflated = inflateRawSync(compressed);
assert.deepEqual(inflated, raw, 'RE2 source must round-trip byte-for-byte');
// Gate execution supplies only exports: reject ESM or non-self-contained builds.
const exports = {};
new Function('exports', inflated.toString())(exports);
assert.equal(exports.RE2JS?.compile('^a+$').matcher('aaa').find(), true,
  're2js require export must be a self-contained CJS engine');
assert.equal(exports.RE2JS.compile('^a+$').matcher('bbb').find(), false);

const destination = join(sdk, 'src/re2js-embedded.ts');
let current = false;
if (existsSync(destination)) {
  const source = readFileSync(destination, 'utf8');
  const oldVersion = source.match(/export const RE2JS_VERSION = '([^']+)';/)?.[1];
  const oldBlob = source.match(/export const RE2JS_DEFLATED_BASE64 = '([A-Za-z0-9+/=]+)';/)?.[1];
  if (oldVersion === version && oldBlob) {
    try { current = inflateRawSync(Buffer.from(oldBlob, 'base64')).equals(raw); }
    catch { /* A corrupt generated blob is stale and must be regenerated. */ }
  }
}
// Preserve committed compressed bytes across zlib builds when the source agrees.
if (current) {
  console.log(`re2js ${version} embed is current`);
} else if (values.check) {
  console.error('re2js embed is stale; run npm run gen:re2js --prefix packages/sdk');
  process.exitCode = 1;
} else {
  writeFileSync(destination,
    '// GENERATED by scripts/generate-re2js-embed.mjs — do not edit.\n'
    + `export const RE2JS_VERSION = '${version}';\n`
    + `export const RE2JS_DEFLATED_BASE64 = '${compressed.toString('base64')}';\n`);
  console.log(`Generated re2js ${version} embed`);
}
